// PROXIMUS v3.5.0 | Entertainment Overdrive schema, rendering and additive UI checks.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {OVERDRIVE_SCHEMA,BUILTIN_SCENES,normalizeScene,normalizeOverdriveSettings,currentScene,exportOverdrivePack,importOverdrivePack,displayProfile,averageFrameColor,hexToRGB,mixRGB} from '../overdrive-core.js';
const ROOT=path.resolve(import.meta.dirname,'..'),read=pathName=>fs.readFileSync(path.join(ROOT,pathName),'utf8');
const html=read('index.html'),app=read('app.js'),styles=read('overdrive.css'),view=read('entertainment-overdrive.js'),sw=read('sw.js');
assert.equal(BUILTIN_SCENES.length,5);
assert.deepEqual(hexToRGB('#8c6aff'),[140,106,255]);
assert.deepEqual(mixRGB([100,0,0],[0,100,0],0.5),[50,50,0]);
assert.deepEqual(averageFrameColor(new Uint8ClampedArray([220,30,60,255,0,0,0,255])),[220,30,60]);
assert.deepEqual(averageFrameColor(new Uint8ClampedArray([0,0,0,255]),[1,2,3]),[1,2,3]);
assert.equal(displayProfile('auto',{width:390,coarse:true}).mode,'efficiency');
assert.equal(displayProfile('auto',{width:1440,coarse:false}).mode,'balanced');
assert.equal(displayProfile('overdrive',{width:1440}).mode,'overdrive');
assert.equal(displayProfile('overdrive',{reducedMotion:true}).mode,'efficiency');
assert.equal(normalizeScene({id:'custom-ok',name:'  My scene ',color:'#ABCDEF',palette:'gold'}).name,'My scene');
assert.equal(normalizeScene({id:'evil',name:'Unsafe',color:'red',palette:'violet'}),null);
const preset={id:'custom-saved',name:'My Atmosphere',color:'#bc47e3',palette:'violet'};
const normalized=normalizeOverdriveSettings({sceneId:preset.id,quality:'overdrive',ambient:false,glow:140,customScenes:[preset]});
assert.equal(normalized.sceneId,preset.id);
assert.equal(normalized.glow,100);
assert.equal(normalized.ambient,false);
assert.equal(currentScene(normalized).color,'#bc47e3');
const pack=exportOverdrivePack(normalized);
assert.equal(pack.schema,OVERDRIVE_SCHEMA);
assert.deepEqual(importOverdrivePack(JSON.parse(JSON.stringify(pack))),normalized);
assert.throws(()=>importOverdrivePack({schema:'wrong',settings:{}}),/compatible/);
assert.equal(normalizeOverdriveSettings({sceneId:'unlisted',quality:'unsafe',glow:-1}).sceneId,'nebula');
assert.equal(normalizeOverdriveSettings({sceneId:'unlisted',quality:'unsafe',glow:-1}).quality,'auto');
assert.equal(normalizeOverdriveSettings({customScenes:Array.from({length:30},(_,i)=>({id:'custom-'+i,name:'Scene '+i,color:'#aa77cc',palette:'violet'}))}).customScenes.length,20);
assert.throws(()=>importOverdrivePack({schema:OVERDRIVE_SCHEMA,settings:{customScenes:Array.from({length:21},()=>preset)}}),/too many/);
for(const id of ['overdriveHub','overdriveScene','overdriveSceneName','overdriveColor','overdriveQuality','overdriveAtmosphere','overdriveGlow','overdriveStatus','overdriveCinemaStatus','overdriveSave','overdriveDelete','overdriveExport','overdriveImport','overdriveToProjects','overdriveCinemaJump']){
 assert.equal((html.match(new RegExp('id="'+id+'"','g'))||[]).length,1,'Missing or duplicated Overdrive control '+id);
}
for(const target of ['videos','reactor','arcade','animation'])assert.ok(html.includes('data-overdrive-target="'+target+'"'),'Missing existing-space launch '+target);
assert.match(html,/Infinite Realms/);
assert.match(html,/PLANNED · v3\.5\.3/);
assert.match(view,/app\.changeView\(target\)/);
assert.match(view,/saveOrShare/);
assert.match(view,/getImageData/);
assert.match(view,/catch\{/);
assert.ok(styles.includes('@media(max-width:420px)'),'Small iPhone layout missing');
assert.ok(styles.includes('prefers-reduced-motion'),'Reduced motion fallback missing');
assert.ok(sw.includes("'./overdrive-core.js'")&&sw.includes("'./entertainment-overdrive.js'")&&sw.includes("'./overdrive.css'"));
assert.match(app,/initEntertainmentOverdrive\(app\)/);
assert.equal([...html.matchAll(/<section class="studio" data-panel="([^"]+)"/g)].length,20,'Existing 18 companion spaces plus 2 information pages must remain unchanged');
assert.equal([...html.matchAll(/class="nav[^"]*" data-view="([^"]+)"/g)].length,20,'No navigation clutter permitted');
console.log('PASS: Entertainment Overdrive v3.5.0 scene schema, color sampling, controls, responsiveness and preserved navigation');
