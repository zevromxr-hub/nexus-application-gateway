// Sovereign Reactor v2.7 — deterministic DSP and responsive rendering tests.
import assert from 'node:assert/strict';
import {REACTOR_THEMES,spectralBands,initialBeatState,detectBeat,normalizeReactorPreset,reactorDimensions} from '../reactor-dsp.js';
const silence=spectralBands(new Uint8Array(1024),48000,2048);
assert.deepEqual(silence,{sub:0,bass:0,mid:0,treble:0,energy:0});
const beats=new Uint8Array(1024),bassHz=48000/2048;
for(let hz=45;hz<170;hz+=bassHz)beats[Math.round(hz/bassHz)]=245;
const band=spectralBands(beats,48000,2048);
assert.ok(band.bass>.6,'Bass band must respond to low-frequency bins');
assert.ok(band.treble<.01,'Treble should not falsely react to bass bins');
const highs=new Uint8Array(1024);
for(let hz=2400;hz<6000;hz+=bassHz)highs[Math.round(hz/bassHz)]=240;
const treble=spectralBands(highs,48000,2048);
assert.ok(treble.treble>.5,'High-frequency band should respond to treble');
assert.ok(treble.bass<.01,'Low bass should not respond to high frequencies');
const start=initialBeatState();
assert.equal(start.kicks,0);
const pulse=detectBeat({bass:.86,sub:.8},1000,start,1.3);
assert.equal(pulse.hit,true);
assert.equal(pulse.kicks,1);
const withinCooldown=detectBeat({bass:.94,sub:.89},1100,pulse,1.3);
assert.equal(withinCooldown.hit,false,'Beat cooldown prevents double counts');
const next=detectBeat({bass:.95,sub:.89},1600,withinCooldown,1.3);
assert.equal(next.hit,true);
assert.equal(next.kicks,2);
const quiet=detectBeat({bass:0,sub:0},2200,initialBeatState());
assert.equal(quiet.hit,false,'No fabricated beats without audio energy');
const normalized=normalizeReactorPreset({theme:'frost',mode:'rings',quality:'eco',sensitivity:12,impact:-5,layers:9,signature:'MY BRAND',snow:true});
assert.equal(normalized.theme,'frost');
assert.equal(normalized.mode,'rings');
assert.equal(normalized.sensitivity,2.5);
assert.equal(normalized.impact,.5);
assert.equal(normalized.layers,1);
assert.equal(normalized.signature,'MY BRAND');
assert.equal(normalized.snow,true);
assert.equal(normalizeReactorPreset({theme:'nope',mode:'not-a-mode'}).theme,'void');
assert.equal(Object.keys(REACTOR_THEMES).length,5);
assert.deepEqual(reactorDimensions('eco'),{width:640,height:360,fps:24});
assert.deepEqual(reactorDimensions('balanced'),{width:960,height:540,fps:36});
assert.deepEqual(reactorDimensions('cinema'),{width:1280,height:720,fps:45});
console.log('PASS Reactor DSP: silence, bass-vs-treble isolation, beat gating, theme presets and mobile performance profiles.');
