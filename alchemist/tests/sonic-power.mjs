// PROXIMUS v3.5.4 Mobile Power Guard — conservative rendering behavior, no thermal hardware access.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {POWER_KEY,POWER_MODES,normalizePower,isAppleMobileAgent,powerPlan,frameDue} from '../sonic-power.js';
const ROOT=path.resolve(import.meta.dirname,'..'),read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const html=read('index.html'),app=read('app.js'),reactor=read('reactor-studio.js'),
 theater=read('media-theater.js'),style=read('sonic-power.css'),
 service=read('sw.js'),sync=read('workspace-sync.js'),recovery=read('recovery-center.js');
assert.equal(POWER_KEY,'proximus-sonic-power-v1');
assert.deepEqual(POWER_MODES,['auto','cool','audio','smooth']);
assert.deepEqual(normalizePower(),{mode:'auto'});
assert.deepEqual(normalizePower({mode:'unsupported',thermal:'999'}),{mode:'auto'});
assert.equal(normalizePower({mode:'cool'}).mode,'cool');
assert.equal(isAppleMobileAgent('Mozilla/5.0 (iPhone; CPU iPhone OS 26_1 like Mac OS X)'),true);
assert.equal(isAppleMobileAgent('Mozilla/5.0 (iPad; CPU OS 18_7 like Mac OS X)'),true);
assert.equal(isAppleMobileAgent('Mozilla/5.0 (Windows NT 10.0; Win64; x64)'),false);
const desktop=powerPlan({mode:'auto'},{mobile:false,quality:'cinema'});
assert.equal(desktop.limited,false);
assert.equal(desktop.fps,45);
assert.equal(desktop.quality,'cinema');
assert.equal(desktop.width,null);
const iphone=powerPlan({mode:'auto'},{mobile:true,quality:'cinema'});
assert.equal(iphone.limited,true);
assert.equal(iphone.fps,24);
assert.equal(iphone.width,640);
assert.equal(iphone.height,360);
assert.equal(iphone.quality,'eco');
assert.equal(iphone.backgroundPause,false);
assert.equal(iphone.siteAmbientPause,true);
const cool=powerPlan({mode:'cool'},{mobile:true,quality:'cinema'});
assert.equal(cool.fps,15);
assert.equal(cool.width,480);
assert.equal(cool.height,270);
assert.equal(cool.backgroundPause,true);
assert.equal(cool.siteAmbientPause,true);
const audio=powerPlan({mode:'audio'},{mobile:true,quality:'balanced'});
assert.equal(audio.fps,0);
assert.equal(audio.draw,false);
assert.equal(audio.backgroundPause,true);
assert.equal(audio.siteAmbientPause,true);
const smooth=powerPlan({mode:'smooth'},{mobile:true,quality:'cinema'});
assert.equal(smooth.fps,30);
assert.equal(smooth.width,640);
assert.equal(smooth.quality,'eco');
const reduced=powerPlan({mode:'auto'},{mobile:true,reducedMotion:true});
assert.equal(reduced.fps,15);
const slow=powerPlan({mode:'auto'},{mobile:true,autoSlow:true});
assert.equal(slow.fps,15);
assert.equal(powerPlan({mode:'cool'},{mobile:false}).fps,15,'Explicit desktop cool setting should work');
for(const mode of POWER_MODES){
 const record=powerPlan({mode},{mobile:true,quality:'cinema',recording:true});
 assert.equal(record.limited,false,'Recording must retain original detail for '+mode);
 assert.equal(record.draw,true);
 assert.equal(record.width,null);
 assert.equal(record.quality,'cinema');
}
assert.equal(frameDue(1000,0,24),true);
assert.equal(frameDue(1000,990,24),false);
assert.equal(frameDue(1050,1000,24),true);
assert.equal(frameDue(1000,0,0),false);
assert.equal(frameDue(Number.NaN,0,24),false);
assert.equal((html.match(/id="sonicPowerMode"/g)||[]).length,1);
assert.equal((html.match(/id="sonicPowerStatus"/g)||[]).length,1);
assert.equal((html.match(/id="sonicPowerControls"/g)||[]).length,1);
for(const value of POWER_MODES)assert.ok(html.includes('<option value="'+value+'"'),'Power Guard preset '+value);
assert.ok(reactor.includes('powerPlan(powerSettings,'),'Reactor should apply power policy');
assert.ok(reactor.includes('frameDue(now,previous,power.fps)'),'Reactor draws at limited FPS');
assert.ok(reactor.includes('!stageVisible'),'Viewport visibility suspends unnecessary drawing');
assert.ok(reactor.includes('getPowerPlan().quality'),'Reactor uses reduced particles and effects');
assert.ok(reactor.includes('exportingFrame=true;resize()'),'PNG export should retain original quality');
assert.ok(reactor.includes('recording=true;recordChunks=[];resize()'),'Video exports should retain original resolution');
assert.ok(reactor.includes('loopCapturing=true;resize()'),'GIF exports should retain original renderer size');
assert.ok(reactor.includes('pausedBackdropElements'),'Cool mode should pause Reactor background videos');
assert.ok(reactor.includes('pausedSiteVideos'),'Background site videos should be paused, not just hidden');
assert.ok(reactor.includes('No temperature data is collected'),'No false thermal readings');
assert.ok(reactor.includes('const observer=new IntersectionObserver'),'Pause rendering when stage is out of view');
assert.ok(reactor.includes('autoSlow=true'),'Automatically reduce workload if the actual FPS falls');
assert.ok(theater.includes("if(!$('sonicTheaterAdvanced')?.open)return"),'Hidden advanced visualizer must not be painted');
assert.ok(theater.includes("const gap=power==='audio'?Infinity"),'Music-only mode should skip all extra visualization updates');
assert.ok(theater.includes("new CustomEvent('proximus-sonic-spectrum'"),'Music still powers live Reactor on demand');
assert.ok(theater.includes('createMediaElementSource(el)'),'Music playback should remain connected to one Web Audio graph');
assert.ok(style.includes('.sonic-power-ambient-off #ambientMedia'),'Suppress global animated wallpaper while in Reactor');
assert.ok(style.includes('@media(max-width:720px)'),'Mobile controls must remain usable');
assert.ok(service.includes("'./sonic-power.js'")&&service.includes("'./sonic-power.css'"),'Power Guard must be offline cached');
assert.ok(sync.includes(POWER_KEY)&&recovery.includes(POWER_KEY),'Power preferences should survive settings backup');
assert.ok(reactor.includes("SONIC_KEY"),'Legacy Sonic Dimension profiles retained');
assert.ok(reactor.includes("SETTINGS='proximus-reactor-settings-v1'"),'Existing Reactor visual settings storage retained');
assert.ok(html.includes('id="theaterMusicAutostart"')&&html.includes('id="theaterMusicSavedList"'),'Saved music and Play on Start remain accessible');
assert.equal([...html.matchAll(/<section class="studio" data-panel="([^"]+)"/g)].length,20,'No new studio or disruptive menu');
console.log('PASS v3.5.4: iPhone 24/15/0/30 FPS modes, reduced canvas work, offscreen render suspension, preserved high-quality exports, saved music and privacy.');
