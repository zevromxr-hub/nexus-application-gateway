// PROXIMUS v2.6 — portable project, PDF, QR, workflow and device file export tests.
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
if(!globalThis.crypto)globalThis.crypto=webcrypto;
import {makeZip} from '../core.js';
import {parseStoreZip} from '../portable-kit.js';
import {projectManifest,unpackProjectZip} from '../project-hub.js';
import {normalizeRecipe,CREATOR_PRESETS} from '../automation-lab.js';
import {captureSize,CAPTURE_PRESETS} from '../capture-studio.js';
import {createImagePdf} from '../document-forge.js';
import {qrMatrix,qrSvg} from '../qr-studio.js';
import {backupSettings,restoreSettings} from '../recovery-center.js';
const files=[{name:'art.png',data:new Blob([Uint8Array.of(1,2,3)],{type:'image/png'}),studio:'Image Studio'},
 {name:'video.gif',data:new Blob([Uint8Array.of(71,73,70,56,57,97)],{type:'image/gif'}),studio:'Animation Forge'}];
const manifest=projectManifest('Cross-device test',files,'notes');
assert.equal(manifest.schema,'proximus.project/1');
const zip=await makeZip([{name:'project.json',data:new Blob([JSON.stringify(manifest)])},
 ...files.map((f,i)=>({name:manifest.items[i].entry,data:f.data}))]);
const entries=parseStoreZip(await zip.arrayBuffer());
assert.equal(entries.length,3);
const imported=unpackProjectZip(await zip.arrayBuffer());
assert.equal(imported.assets.length,2);
assert.equal(imported.title,'Cross-device test');
assert.equal(imported.notes,'notes');
assert.deepEqual(new Uint8Array(await imported.assets[0].data.arrayBuffer()),Uint8Array.of(1,2,3));
assert.throws(()=>parseStoreZip(Uint8Array.of(0,1,2,3)),/Invalid/);
assert.equal(normalizeRecipe(CREATOR_PRESETS.youtube).width,1280);
assert.equal(normalizeRecipe(CREATOR_PRESETS.discord).icons,true);
assert.throws(()=>normalizeRecipe({width:9000,height:10}),/dimensions/);
assert.deepEqual(captureSize(4032,3024,'discord'),{width:512,height:512});
assert.deepEqual(captureSize(1080,1920,'original'),{width:1080,height:1920});
assert.equal(CAPTURE_PRESETS.phone.height,2532);
const jpeg=Uint8Array.from([0xff,0xd8,0xff,0xe0,...Array(36).fill(0),0xff,0xd9]);
const pdf=createImagePdf([{width:320,height:240,jpeg},{width:320,height:240,jpeg}],{paper:'letter',title:'Test pages',watermark:'PROXIMUS'});
const pdfText=await pdf.text();
assert.ok(pdfText.startsWith('%PDF-1.4'));
assert.match(pdfText,/\/Count 2/);
assert.match(pdfText,/\/DCTDecode/);
assert.match(pdfText,/startxref/);
assert.match(pdfText,/%%EOF/);
const qr1=qrMatrix('HELLO PROXIMUS');
assert.equal(qr1.length,29);
assert.equal(qr1[3][3],true);
const qr2=qrMatrix('https://zevromxr-hub.github.io/nexus-application-gateway/alchemist/');
assert.equal(qr2.length,37);
assert.ok(qr2.flat().filter(Boolean).length>200);
assert.match(qrSvg(qr1),/<svg/);
assert.throws(()=>qrMatrix('x'.repeat(130)),/106/);
const storage={data:new Map(),getItem(k){return this.data.has(k)?this.data.get(k):null;},setItem(k,v){this.data.set(k,v);}};
storage.setItem('proximus-automations-v1','[{"name":"Preset"}]');
const backup=backupSettings(storage);
assert.equal(backup.schema,'proximus.settings/1');
const fresh={data:new Map(),getItem(k){return this.data.get(k)||null;},setItem(k,v){this.data.set(k,v);}};
assert.equal(restoreSettings(fresh,backup),1);
assert.equal(fresh.getItem('proximus-automations-v1'),'[{"name":"Preset"}]');
console.log('PASS v2.6 portable project ZIP, snapshots, automation, capture, multi-page PDF, QR, recovery settings');
