import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const read=p=>readFile(new URL('../'+p,import.meta.url),'utf8');
const [page,atlas,intel,css,loot,items,version,index]=await Promise.all(['world-atlas.html','world-discovery-v23.js','atlas-intelligence-v24.js','atlas-intelligence-v24.css','loot-sources.json','item-atlas.js','version.json','releases/index.json'].map(read));
new vm.Script(atlas);new vm.Script(intel);
assert.ok(page.indexOf('world-discovery-v23.js')<page.indexOf('atlas-intelligence-v24.js'));
assert.ok(atlas.includes('NexusAtlasIntelligenceV24?.decorate'));
assert.ok(atlas.includes('NexusAtlasIntelligenceV24?.extraEntries'));
assert.ok(intel.includes("fetch('./loot-sources.json'"));
assert.ok(intel.includes('nexus_azeroth_item_atlas_v1'));
assert.ok(intel.includes('nexus_azeroth_loot_hunter_v1'));
assert.ok(intel.includes("'/api/search/'")&&intel.includes("'/api/item/'"));
assert.ok(items.includes("'/api/search/'")&&items.includes("'/api/item/'"));
assert.ok(intel.includes('SOURCE REFERENCES · OPTIONAL'));
assert.ok(intel.includes('ADD FARM GOAL')&&intel.includes('+ LOG ATTEMPT'));
assert.ok(intel.includes('DOCUMENTED SAMPLE LOOT'));
assert.ok(intel.includes('OTHER DOCUMENTED PLACES IN THIS ZONE'));
assert.ok(!/BLIZZARD_CLIENT_SECRET|BLIZZARD_CLIENT_ID|nexus_atlas_waypoints_v22.*setItem/.test(intel));
assert.ok(JSON.parse(loot).items.length>=4);
assert.equal(JSON.parse(version).version,'24.0.0');
assert.equal(JSON.parse(index).releases[0].version,'24.0.0');
assert.equal(css.split('{').length,css.split('}').length);
console.log('PASS v24 source: in-app official data, shared tracker formats, internal acquisition and optional sources');
