import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
const base=new URL('../',import.meta.url);
const read=p=>readFile(new URL(p,base),'utf8');
const [atlas,real,discovery,css,version,releases]=await Promise.all(['world-atlas.html','atlas-real-map-v22.1.js','atlas-discovery-v22.3.js','atlas-discovery-v22.3.css','version.json','releases/index.json'].map(read));
new vm.Script(real);new vm.Script(discovery);
assert.ok(real.includes('NexusRealMapDiscoveryV223'));
assert.ok(real.includes('catalog:maps.map('));
assert.ok(real.includes('open:(id,pointId)'));
assert.ok(discovery.includes("input.addEventListener('input'"));
assert.ok(discovery.includes('stopImmediatePropagation'));
assert.ok(discovery.includes('bridge.open(p.zoneId,p.id)'));
assert.ok(discovery.includes('encodeURIComponent(linkQ)'));
assert.ok(discovery.includes('www.wowhead.com/search?q='));
for(const category of ['instances','gathering','travel','other'])assert.ok(discovery.includes(category));
assert.ok(!/localStorage\.setItem|localStorage\.removeItem|fetch\(|eval\(/.test(discovery));
assert.ok(atlas.includes('atlas-discovery-v22.3.js?v=2230'));
assert.equal(JSON.parse(version).version,'22.3.0');
assert.equal(JSON.parse(releases).releases[0].version,'22.3.0');
assert.equal(css.split('{').length,css.split('}').length);
console.log('PASS v22.3 Atlas Discovery: source-index search, map focus, safe external lookup and no destructive storage');
